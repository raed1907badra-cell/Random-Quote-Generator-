def test_json_storage():
    """Тестирование работы с JSON"""
    print("\n" + "=" * 50)
    print("ТЕСТИРОВАНИЕ РАБОТЫ С JSON")
    print("=" * 50)
    
    test_file = "quotes_data.json"
    
    # Тест 1: Создание файла
    print("\n✓ Тест 1: Создание JSON файла")
    if os.path.exists(test_file):
        print(f"  Статус: Файл существует, размер: {os.path.getsize(test_file)} байт")
    else:
        print("  Статус: Файл будет создан при первом запуске")
    
    # Тест 2: Проверка структуры данных
    print("\n✓ Тест 2: Проверка структуры данных")
    if os.path.exists(test_file):
        try:
            with open(test_file, 'r', encoding='utf-8') as f:
                data = json.load(f)
                print(f"  Количество цитат: {len(data.get('quotes', []))}")
                print(f"  Записей в истории: {len(data.get('history', []))}")
                print(f"  Структура корректна: {'quotes' in data and 'history' in data}")
        except json.JSONDecodeError:
            print("  Статус: Ошибка чтения JSON")

